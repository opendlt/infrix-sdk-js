// @infrix/verify — the state root accumulator check (native, offline).
//
// WHY. An evidence bundle carries the node's state root as of its own finalization. The node anchors its state root only every N canonical blocks (and only when it
// changed), so almost no bundle's root is a root any anchor names, and a verifier that demanded it be the anchored root would refuse nearly every honest bundle. The
// node therefore keeps an append-only Merkle tree of every root it held (one leaf, (canonical height, root), each time its root changed), anchors the sealed root of
// that tree, and an exported bundle carries an inclusion proof of its root's leaf against an anchored seal. A root the node never held is in no anchored seal.
//
// THE TREE is the RFC 9162 Merkle tree: leaf = SHA-256(0x00 || be64(height) || root), node = SHA-256(0x01 || left || right), a node over n leaves splitting at the
// largest power of two below n. The SEALED ROOT the node anchors is SHA-256("infrix-root-history-v1" || be64(n) || treeHash), so what is anchored commits to the
// leaf count as well as the tree.
//
// THIS IS A THIRD IMPLEMENTATION, INDEPENDENT ON PURPOSE (the others are the node's pkg/rootaccum, which makes the proofs, and infrix-verify's stateroot package, which
// verifykit uses). One file of vectors generated by the Infrix runtime pins all three: the seal of every tree size to 40, every leaf's audit path, and a table of
// document cases, a tamper case per outcome of the rule below (test/fixtures/state-root-vectors.json, SHA-256 pinned by test/stateRootAccumulator.test.mjs).
//
// THE RULE (the same in all three): no document SKIPS and leaves every verdict as it was; a document awaiting the next anchor SKIPS saying "unchecked until the next
// anchor"; a proven document is REFUSED when it is for another root than the bundle's, when its path does not compute to the seal it names, when the bundle carries
// no root, when it names no anchor, and, given an L0 reader, when L0 does not list the seal; with no reader a consistent proof SKIPS. It changes no assurance level.
//
// This module is written natively for the SDK (it is not vendored from Nexus); the L0 read is optional and injected: `reader.rootsAt(txHash)` resolves the roots the
// L0 anchor entry lists, as Uint8Array(32) values or 64-character hex strings, taken from L0 itself and never from the node that produced the bundle.

import { sha256, concatBytes, bytesToHex, bytesEqual, coerce32, isZero32 } from './canonicalJson.js';

export const STATE_ROOT_SEAL_DOMAIN = 'infrix-root-history-v1';
export const STATE_ROOT_DOCUMENT_VERSION = 'infrix-state-root-proof-v1';
export const STATE_ROOT_DOCUMENT_KEY = 'stateRootProof';
export const STATE_ROOT_CHECK_NAME = 'state_root_accumulator';

const enc = new TextEncoder();

function be64(n) {
  const out = new Uint8Array(8);
  new DataView(out.buffer).setBigUint64(0, BigInt(n), false);
  return out;
}

async function leafHash(height, root) {
  return sha256(concatBytes(concatBytes(Uint8Array.of(0x00), be64(height)), root));
}

async function nodeHash(left, right) {
  return sha256(concatBytes(concatBytes(Uint8Array.of(0x01), left), right));
}

async function seal(size, treeHash) {
  return sha256(concatBytes(concatBytes(enc.encode(STATE_ROOT_SEAL_DOMAIN), be64(size)), treeHash));
}

function decode32(hex) {
  if (typeof hex !== 'string' || !/^[0-9a-fA-F]*$/.test(hex) || hex.length % 2 !== 0) {
    throw new Error('not hex');
  }
  if (hex.length !== 64) throw new Error(`${hex.length / 2} bytes, want 32`);
  const out = new Uint8Array(32);
  for (let i = 0; i < 32; i++) out[i] = parseInt(hex.slice(2 * i, 2 * i + 2), 16);
  return out;
}

const short = (h) => (h.length > 16 ? `${h.slice(0, 16)}...` : h);

/**
 * The sealed root an inclusion proof commits to, recomputed from its leaf and audit path alone (RFC 9162 section 2.1.3.2), for leaf number `index` of a tree of
 * `size` leaves. Throws for a path of the wrong length for that index and size.
 */
export async function sealedRootOf(index, size, height, root, path) {
  let fn = BigInt(index);
  let sn = BigInt(size) - 1n;
  if (BigInt(size) === 0n || BigInt(index) >= BigInt(size)) throw new Error('the proof does not prove inclusion');
  let acc = await leafHash(height, root);
  for (const sibling of path) {
    if (sn === 0n) throw new Error('the proof does not prove inclusion');
    if ((fn & 1n) === 1n || fn === sn) {
      acc = await nodeHash(sibling, acc);
      while ((fn & 1n) === 0n && fn !== 0n) {
        fn >>= 1n;
        sn >>= 1n;
      }
    } else {
      acc = await nodeHash(acc, sibling);
    }
    fn >>= 1n;
    sn >>= 1n;
  }
  if (sn !== 0n) throw new Error('the proof does not prove inclusion');
  return seal(size, acc);
}

const skip = (detail) => ({ verdict: 'skip', detail });
const fail = (detail) => ({ verdict: 'fail', detail });

/**
 * Judge a bundle's state root against the document an export attached beside the package.
 * @param {object|null|undefined} doc the stateRootProof document (null/undefined: none attached)
 * @param {Uint8Array} bundleRoot the bundle's own state root (32 bytes)
 * @param {{rootsAt(txHash: string): Promise<Array<Uint8Array|string>>}|null} [reader] reads the roots an L0 anchor entry lists; null/undefined: no L0 endpoint
 * @returns {Promise<{verdict: 'pass'|'fail'|'skip', detail: string}>}
 */
export async function checkStateRootProof(doc, bundleRoot, reader) {
  if (doc === null || doc === undefined) {
    return skip('no state root proof is attached to this bundle: its state root is unchecked (bundles exported before the node kept a root history carry none)');
  }
  if (doc.version !== STATE_ROOT_DOCUMENT_VERSION) {
    return skip(`the attached state root proof is version "${doc.version}", which this verifier does not read: the bundle's state root is unchecked`);
  }
  switch (doc.status) {
    case 'awaiting_anchor':
      return skip(
        `finalized after the newest anchor: the bundle's state root is in the node's history (leaf at canonical height ${doc.leafHeight ?? 0}, history now ${doc.currentSize ?? 0} leaves) but the newest anchored seal covers only ${doc.newestAnchoredSize ?? 0}, so it is unchecked until the next anchor; re-export or re-attach the proof then`,
      );
    case 'unavailable':
      return skip(`the node could not prove the bundle's state root: ${doc.reason ?? ''}`);
    case 'proven':
      break;
    default:
      return skip(`the attached state root proof has status "${doc.status}", which this verifier does not read: the bundle's state root is unchecked`);
  }
  if (isZero32(bundleRoot)) {
    return fail('a state root proof is attached to a bundle that carries no state root');
  }
  let leafRoot;
  try {
    leafRoot = decode32(doc.stateRoot);
  } catch (e) {
    return fail(`the attached state root proof is malformed: stateRoot: ${e.message}`);
  }
  const path = [];
  const docPath = doc.path ?? [];
  for (let i = 0; i < docPath.length; i++) {
    try {
      path.push(decode32(docPath[i]));
    } catch (e) {
      return fail(`the attached state root proof is malformed: path[${i}]: ${e.message}`);
    }
  }
  if (!bytesEqual(leafRoot, bundleRoot)) {
    return fail(`the proof is for state root ${doc.stateRoot} but the bundle carries ${bytesToHex(bundleRoot)}`);
  }
  let named;
  try {
    named = decode32(doc.accumulatorRoot);
  } catch (e) {
    return fail(`the attached state root proof names a malformed accumulator root: ${e.message}`);
  }
  let computed = null;
  let why = 'the proof does not prove inclusion';
  try {
    computed = await sealedRootOf(doc.leafIndex ?? 0, doc.treeSize ?? 0, doc.leafHeight ?? 0, leafRoot, path);
  } catch (e) {
    why = e.message;
  }
  if (computed === null || !bytesEqual(computed, named)) {
    return fail(`the bundle's state root does not prove into the accumulator root the document names (${doc.accumulatorRoot}): ${why}`);
  }
  if (!reader) {
    return skip(
      `the bundle's state root proves into accumulator root ${short(doc.accumulatorRoot)} (leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0}), but no L0 endpoint was supplied, so that the node anchored that root is not independently confirmed`,
    );
  }
  if (!doc.anchor || !doc.anchor.txHash) {
    return fail('the attached state root proof names no L0 anchor transaction for its accumulator root');
  }
  let listed;
  try {
    listed = await reader.rootsAt(doc.anchor.txHash);
  } catch (e) {
    return fail(`could not read the accumulator anchor from L0: ${e.message}`);
  }
  for (const r of listed) {
    const bytes = typeof r === 'string' ? decode32(r) : r;
    if (bytesEqual(bytes, named)) {
      return {
        verdict: 'pass',
        detail: `the bundle's state root is leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0} in the node's root history, whose sealed root ${short(doc.accumulatorRoot)} L0 lists in anchor transaction ${short(doc.anchor.txHash)}`,
      };
    }
  }
  return fail(`the accumulator root ${short(doc.accumulatorRoot)} is not listed in the L0 anchor entry of transaction ${short(doc.anchor.txHash)}: the node never anchored it`);
}

/**
 * The state root of an exported package, read from its embedded bundle (a 32-element number array or a hex string, as the package encodes it).
 */
export function bundleStateRoot(pkg) {
  const raw = typeof pkg.bundleData === 'string' ? JSON.parse(pkg.bundleData) : pkg.bundleData;
  return coerce32(raw.stateRoot);
}

/**
 * The state_root_accumulator check of an exported file: the package (bare, or under "bundle") and the sibling `stateRootProof` document beside it.
 * `options.require` turns every skip into a failure (a verifier that accepts only a bundle whose state root is proven).
 */
export async function verifyStateRootOfExport(file, reader, options = {}) {
  const pkg = file.bundleData !== undefined ? file : file.bundle;
  let result;
  try {
    result = await checkStateRootProof(file[STATE_ROOT_DOCUMENT_KEY], bundleStateRoot(pkg), reader);
  } catch (e) {
    result = fail(`the bundle's state root could not be read: ${e.message}`);
  }
  if (options.require && result.verdict === 'skip') {
    result = fail(`a proven state root is required but it is not: ${result.detail}`);
  }
  return { name: STATE_ROOT_CHECK_NAME, ...result };
}
